#!/usr/bin/env python3
"""BENCH (docs/tasks/2.1.0/13): renders the canonical baseline markdown from JMH
JSON result files. BENCHMARKS.md baseline tables are GENERATED by this script from
full-run JSON — never hand-typed (traceability: every number binds to a result
file + run manifest in the results directory).

Usage: python3 scripts/render-bench-baseline.py <jmh-results.json> [more.json ...]
Prints one markdown table per benchmark CLASS (the harness family grouping), with
scenario + params rows sorted for stable diffs.
"""
import json
import sys


def render(paths):
    families = {}
    for path in paths:
        with open(path) as f:
            data = json.load(f)
        for bench in data:
            name = bench["benchmark"]
            parts = name.split(".")
            cls = parts[-2]   # io.github...performance.<Class>.<method>
            scenario = parts[-1]
            params = bench.get("params", {})
            ptxt = ", ".join(f"{k}={v}" for k, v in sorted(params.items())) or "—"
            p = bench["primaryMetric"]
            rows = families.setdefault(cls, {})
            rows[(scenario, ptxt)] = (p["score"], p.get("scoreError", 0.0), p.get("scoreUnit", "ops/s"))

    out = []
    for cls in sorted(families):
        out.append(f"#### `{cls}`\n")
        out.append("| Scenario | Params | ops/s ± error |")
        out.append("|---|---|---|")
        for (scenario, ptxt), (score, err, unit) in sorted(families[cls].items()):
            out.append(f"| `{scenario}` | {ptxt} | {score:,.0f} ± {err:,.0f} |")
        out.append("")
    return "\n".join(out)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    print(render(sys.argv[1:]))


if __name__ == "__main__":
    main()

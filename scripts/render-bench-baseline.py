#!/usr/bin/env python3
"""BENCH (docs/tasks/2.1.0/13): renders the canonical baseline markdown from JMH
JSON result files. BENCHMARKS.md baseline tables are GENERATED by this script from
full-run JSON — never hand-typed (traceability: every number binds to a result
file + run manifest in the results directory).

Usage: python3 scripts/render-bench-baseline.py <jmh-results.json> [more.json ...]
Prints one markdown table per benchmark CLASS (the harness family grouping), with
scenario + params rows sorted for stable diffs.
"""
import json
import sys


def render_design_point(paths):
    """N50K (docs/tasks/2.1.0/20): the design-point probe JSON (a 'probe'-keyed document,
    not a JMH array) -> the N=5k vs N=50k comparison tables + heap rows."""
    runs = []
    meta = {}
    for path in paths:
        with open(path) as f:
            data = json.load(f)
        if not isinstance(data, dict) or data.get("probe") != "design-point":
            continue
        meta = data
        runs.extend(data.get("runs", []))
    if not runs:
        return None

    lines = []
    lines.append("| N | heap bytes/object | bulk load obj/s | range window hits |")
    lines.append("|---|---|---|---|")
    for run in runs:
        lines.append(f"| {run['n']:,} | {run['heap']['bytesPerObject']:,.0f} | "
                     f"{run['bulkLoad']['objectsPerSec']:,.0f} | {run.get('rangeWindowHits', '—'):,} |")
    lines.append("")

    scen = {}
    for run in runs:
        for name, v in run["scenarios"].items():
            scen.setdefault(name, {})[run["n"]] = (v["opsPerSec"], v["status"])
    lines.append("| Scenario (probe mode, single run) | N=5 000 ops/s | N=50 000 ops/s | status |")
    lines.append("|---|---|---|---|")
    for name in sorted(scen):
        s5 = scen[name].get(5000, ("—", ""))
        s50 = scen[name].get(50000, ("—", ""))
        status = "ok" if all("ok" in v[1] for v in scen[name].values()) else "TIMEOUT at N=50k (the ceiling finding)"
        lines.append(f"| `{name}` | {s5[0]:,.1f} | {s50[0]:,.1f} | {status} |")
    lines.append("")
    return "\n".join(lines)


def render(paths):
    # a probe document renders as the design-point section, a JMH array as the family tables
    with open(paths[0]) as f:
        head = json.load(f)
    if isinstance(head, dict) and head.get("probe") == "design-point":
        return render_design_point(paths)
    families = {}
    for path in paths:
        with open(path) as f:
            data = json.load(f)
        for bench in data:
            name = bench["benchmark"]
            parts = name.split(".")
            cls = parts[-2]   # io.github...performance.<Class>.<method>
            scenario = parts[-1]
            params = bench.get("params", {})
            ptxt = ", ".join(f"{k}={v}" for k, v in sorted(params.items())) or "—"
            p = bench["primaryMetric"]
            rows = families.setdefault(cls, {})
            rows[(scenario, ptxt)] = (p["score"], p.get("scoreError", 0.0), p.get("scoreUnit", "ops/s"))

    out = []
    for cls in sorted(families):
        out.append(f"#### `{cls}`\n")
        out.append("| Scenario | Params | ops/s ± error |")
        out.append("|---|---|---|")
        for (scenario, ptxt), (score, err, unit) in sorted(families[cls].items()):
            out.append(f"| `{scenario}` | {ptxt} | {score:,.0f} ± {err:,.0f} |")
        out.append("")
    return "\n".join(out)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    print(render(sys.argv[1:]))


if __name__ == "__main__":
    main()

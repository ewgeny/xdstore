package org.flib.xdstorage.serialization.strategies;

import org.flib.xdstorage.utils.XdStorageObjectField;
import java.io.Writer;
import java.util.Collection;

/**
 * Интерфейс контекста сквозной сериализации объектов СУБД.
 * Предоставляет изолированным модулям-стратегиям доступ к общим механизмам
 * форматирования XML, экранирования текста и потокобезопасного кэширования метаданных.
 */
public interface XdStorageXmlWriterContext {

    /**
     * Делегирует сериализацию следующего вложенного объекта (или свойства)
     * глобальному реестру стратегий. Позволяет осуществлять рекурсивный обход
     * сложных древовидных структур данных СУБД.
     *
     * @param name   логическое имя XML-атрибута (название поля Java-класса)
     * @param clazz  актуальный класс сериализуемого объекта
     * @param value  экземпляр объекта с данными
     * @param writer активный символьный поток вывода
     * @param level  текущий уровень вложенности XML-документа для форматирования
     * @throws Exception в случае ошибок рефлексивного доступа или ввода-вывода
     */
    void writeNextObject(String name, Class<?> clazz, Object value, Writer writer, int level) throws Exception;

    /**
     * Записывает в поток символы перевода строки и табуляции, формируя
     * структурированный, удобочитаемый (human-readable) вид XML-документа.
     *
     * @param writer активный символьный поток вывода
     * @param level  количество знаков табуляции, соответствующих текущей глубине вложенности
     * @throws Exception в случае сбоев I/O
     */
    void writeIndent(Writer writer, int level) throws Exception;

    /**
     * Выполняет безопасное экранирование специальных управляющих символов XML
     * (таких как &lt;, &gt;, &amp;, ", '), превращая их в безопасные цифровые сущности (entities).
     * Защищает XML-документ от разрушения структуры при наличии спецсимволов в строковых данных.
     *
     * @param value исходная строка текста
     * @return экранированная строка, безопасная для вставки в XML-атрибуты или текстовые узлы
     */
    String encodeText(String value);

    /**
     * Предоставляет стратегиям доступ к исправленному потокобезопасному кэшу
     * дескрипторов полей класса, исключая накладные расходы на повторную рефлексию.
     *
     * @param clazz класс, метаданные полей которого необходимо извлечь
     * @return коллекция оберток полей XdStorageObjectField для данного класса
     */
    Collection<XdStorageObjectField> getFieldsCache(Class<?> clazz);
}

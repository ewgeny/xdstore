package io.github.xdstorage.serialization;

/**
 * R-43: контракт согласованной сериализации живых объектов. Выгружка ресурса на диск
 * пишет ЖИВОЙ инстанс (канонический реестр B+Tree), пока параллельные транзакции мутируют
 * его поля (сплиты/джойны рвут LinkedList прямо под итератором писателя — CME и рваные
 * XML). Объект, реализующий этот контракт, обязан на время между begin/end гарантировать
 * стабильность своего состояния для чтения.
 */
public interface IXdStorageSerializationGuard {

    /** Зафиксировать состояние объекта на время сериализации (best-effort: при отказе — WARN и запись без замка). */
    void beginConsistentSerialization();

    /** Отпустить состояние объекта после сериализации. */
    void endConsistentSerialization();
}

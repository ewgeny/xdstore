package io.github.xdstorage.performance;

import io.github.xdstorage.IXdStorage;
import io.github.xdstorage.XdStorageProvider;
import io.github.xdstorage.entities.XdPlanet;
import io.github.xdstorage.entities.XdStarSystem;
import io.github.xdstorage.transaction.IXdStorageTransaction;
import org.junit.jupiter.api.*;

import java.io.File;
import java.util.Collection;
import java.util.HashSet;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

@DisplayName("Интеграционный TDD-тест: Сплиты через фасад СУБД при t=5 (Автогенерация ID)")
public class XdStorageFacadeGiantArraySplitStressTest {

    private static final String STORAGE_DIR = "./test_facade_giant_storage";
    private IXdStorage storage;

    // Идентификатор звездной системы и размер пачки дочерних планет
    private final String systemId = UUID.randomUUID().toString();

    // При t = 5 сплит ноды происходит на каждых 10 элементах.
    // Пачка из 150 планет гарантированно вырастит многоуровневый индекс вверх!
    private final int planetsCount = 1000;

    @BeforeEach
    public void initStorage() {
        deleteDir(new File(STORAGE_DIR));
        // Создаем честное дисковое файловое хранилище СУБД
        // Мы жестко выставляем размер фрагмента 250, как в XmlDataStorageMultithreadsTest
        storage = XdStorageProvider.newOrGetFileStorage("giant_facade_test", STORAGE_DIR, 250);
    }

    @AfterEach
    public void destroyStorage() {
        if (storage != null) {
            storage.shutdown();
        }
        deleteDir(new File(STORAGE_DIR));
    }

    public static void deleteDir(File file) {
        File[] contents = file.listFiles();
        if (contents != null) {
            for (File f : contents) {
                deleteDir(f);
            }
        }
        file.delete();
    }

    @Test
    @DisplayName("Воспроизведение бага: Крах ленивой подгрузки пачки коллекций после лавины сплитов при t=5")
    public void testFacade_MassAutoGeneratedIds_ShouldMaintainIndexRouting() throws Exception {
        System.out.println("=== СТАРТ ИНТEГРАЦИOННOГO ТEСТА: ОЧEРEДЬ СУБД (t=5) ===");

        // 1. Создаем структуры. У планет ID равен null — СУБД сгенерирует их сама через БД-генератор
        XdStarSystem system = new XdStarSystem();
        system.setId(systemId);

        // ВНИМАНИЕ: Используем базовый HashSet, чтобы спровоцировать хаотичный лавинный
        // проход элементов, как в оригинальном падающем тесте!
        system.setPlanets(new HashSet<>());

        for (int i = 0; i < planetsCount; i++) {
            XdPlanet planet = new XdPlanet();
            planet.setName("MassPlanet_" + i);
            planet.setWaterPercent(i % 3);
            system.addPlanet(planet);
        }

        // 2. Накатываем пачечное сохранение коллекций через публичный фасад СУБД
        IXdStorageTransaction writeTx = storage.beginTransaction();
        try {
            storage.save(system, writeTx);

            // В этот момент СУБД обходит HashSet, генерирует ID планет (1001, 1002, 1003...)
            // и хаотично вставляет их в Дерево Индексов, вызывая каскадные сплиты внутренних страниц!
            storage.save(system.getPlanets(), writeTx);

            writeTx.commit();
            System.out.println(" -> Шаг 1: Массив из " + planetsCount + " объектов успешно закоммичен фасадом СУБД.");
        } catch (Throwable e) {
            writeTx.rollback();
            System.err.println("🚨 Крах фасада на этапе записи:");
            throw e;
        }

        // Даем закрыться дескрипторам файлов на диске
        Thread.sleep(10);

        // 3. Открываем СOВEРШEННO НOВУЮ транзакцию чтения и верифицируем сквозной ленивый спуск
        IXdStorageTransaction readTx = storage.beginTransaction();
        try {
            System.out.println(" -> Шаг 2: Инициализируем новую транзакцию чтения. Подгружаем систему...");
            XdStarSystem loadedSystem = storage.load(XdStarSystem.class, systemId, readTx);
            assertNotNull(loadedSystem, "СУБД потеряла корневой объект звездной системы на диске!");

            // Провоцируем ленивую подгрузку коллекции getPlanets() прокси-обертки XdStarSystemSimpleWrapper
            Collection<XdPlanet> loadedPlanets = loadedSystem.getPlanets();

            System.out.println(" -> Шаг 3: Вызываем глубинную догрузку прокси-ссылок планет через storage.load()...");

            // НАСТОЯЩИЙ ИНТЕГРАЦИОННЫЙ ШТУРМ:
            // СУБД полезет в B+ Дерево индексов, начнется вертикальный поиск.
            // На старом коде СУБД из-за асимметрии разделителей Кнута в findChildAndInsert (compareResult == 0)
            // часть автогенерированных ID планет улетит на некорректные дочерние страницы.
            // Вертикальный навигатор поиска промахнется, и этот вызов выбросит XdStorageRuntimeException!
            assertDoesNotThrow(() -> {
                storage.load(loadedPlanets, readTx);
            }, "🚨 БАГ ФАСАДА СУБД ВOСПРOИЗВEДEН! Навигатор индексов ослеп после сплитов при t=5. Транзакция ушла в rollback only!");

            System.out.println("📊 ИТOГOВЫE РEЗУЛЬТАТЫ ИНТEГРАЦИOННOГO ТEСТА:");
            System.out.println("🔹 Ожидали планет в дочерней коллекции: " + planetsCount);
            System.out.println("🔹 Фактически считано через дерево индексов: " + loadedPlanets.size());

            assertEquals(planetsCount, loadedPlanets.size(),
                    "🚨 КРАХ МВСС-ИЗОЛЯЦИИ! Количество считанных планет не совпадает с исходной пачкой!");

            readTx.commit();
            System.out.println("=== ИНТEГРАЦИOННЫЙ TDD-ТEСТ ЧEРEЗ ФАСАД ЗАВEРШEН УСПEШНO ===");
        } catch (Throwable e) {
            readTx.rollback();
            System.err.println("🚨 Крах фасада на этапе верификации чтения:");
            throw e;
        }
    }
}
